// site/lib/markdown/plugins/toc-extractor.js - Extracts h2 and h3 headings with stable slug ids for Table of Contents

/**
 * Recursively extracts plain text from a HAST element node, ignoring anchor link symbols.
 *
 * @param {object} node - HAST node
 * @returns {string} Plain text
 */
function getNodeText(node) {
  if (!node) return '';
  if (node.type === 'text') return node.value || '';
  if (node.type === 'element') {
    // Skip anchor link symbol if present
    if (node.properties?.className?.includes('icon-link') || node.properties?.ariaHidden === 'true') {
      return '';
    }
    if (Array.isArray(node.children)) {
      return node.children.map(getNodeText).join('');
    }
  }
  return '';
}

/**
 * Traverses a HAST tree and extracts all h2 and h3 headings with their slug IDs.
 *
 * @param {object} hastTree - HAST tree generated by rehype
 * @returns {Array<{ id: string, text: string, level: number }>} List of extracted headings
 */
export function extractHeadings(hastTree) {
  const headings = [];

  function visit(node) {
    if (node?.type === 'element' && (node.tagName === 'h2' || node.tagName === 'h3')) {
      const id = node.properties?.id;
      const rawText = getNodeText(node).trim();
      // Remove any trailing '#' link artifacts
      const cleanText = rawText.replace(/#$/, '').trim();

      if (id && cleanText) {
        headings.push({
          id: String(id),
          text: cleanText,
          level: parseInt(node.tagName.charAt(1), 10),
        });
      }
    }

    if (Array.isArray(node?.children)) {
      node.children.forEach(visit);
    }
  }

  visit(hastTree);
  return headings;
}

